export function dongyaCurrentTab(ctx){
	const keys = EAST_ASIA_TABS.map((t)=>t.key);
	const explicit = ctx && ctx.innerTab;
	if(explicit && keys.indexOf(explicit) >= 0){ return explicit; }
	try{
		const saved = EAST_ASIA_PAGE_SETTINGS.load().tab;
		return keys.indexOf(saved) >= 0 ? saved : null;
	}catch(e){
		return null;
	}
}

