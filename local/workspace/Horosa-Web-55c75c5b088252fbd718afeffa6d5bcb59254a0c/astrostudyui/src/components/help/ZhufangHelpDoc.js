// 当前子页签:调用方显式给的(ctx.innerTab)优先,否则读本页记住的页签;都没有回总览
export function zhufangCurrentTab(ctx){
	const keys = ZHUFANG_TABS.map((t)=>t.key);
	const explicit = ctx && ctx.innerTab;
	if(explicit && keys.indexOf(explicit) >= 0){ return explicit; }
	try{
		const saved = ZHUFANG_PAGE_SETTINGS.load().tab;
		return keys.indexOf(saved) >= 0 ? saved : null;
	}catch(e){
		return null;
	}
}

