							<p style={p}>「定朔」指按真实日月运行求日月黄经相同的那一刻,该刻所在之日即农历初一;「定气」指按太阳真实黄经每到十五度整数倍即交节,而非把一年平均分成二十四段。本页两者都取定法,故节气与朔都能给到时分秒。</p>

