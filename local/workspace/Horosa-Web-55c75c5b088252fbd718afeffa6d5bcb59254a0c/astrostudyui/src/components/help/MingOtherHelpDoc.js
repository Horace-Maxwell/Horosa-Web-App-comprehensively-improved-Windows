// 一个技法的多章合排成一章(左栏父级菜单只列技法,右栏是该技法的整本手册)
function combined(chapters){
	return ()=>(
		<div>
			{chapters.map((c, i)=>{
				let content = null;
				try{ content = c.render(); }catch(e){ content = null; }
				return (
					<div key={c.key} style={i ? { marginTop: 26 } : null}>
						{i ? <div style={title}>{c.label}</div> : null}
						{content}
					</div>
				);
			})}
		</div>
	);
}

