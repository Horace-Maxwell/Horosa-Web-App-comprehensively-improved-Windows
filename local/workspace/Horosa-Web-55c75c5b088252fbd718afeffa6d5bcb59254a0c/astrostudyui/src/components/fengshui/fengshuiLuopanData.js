export const YAO384_TICKS = (()=>{
	const per = 360 / 384;
	const out = [];
	for (let i = 0; i < 384; i++) {
		out.push({ idx: i, deg0: norm360(i * per), deg1: norm360((i + 1) * per), yao: (i % 6) + 1 });
	}
	return out;
})();

