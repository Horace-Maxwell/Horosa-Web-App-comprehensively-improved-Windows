//   太阳到山盘：立春自壬始，雨水惊蛰等按**逆时针**排列。
//   太阴到山盘：立春自艮始，雨水惊蛰等按**顺时针**排列。
export const JIEQI_24 = ['立春', '雨水', '惊蛰', '春分', '清明', '谷雨', '立夏', '小满',
	'芒种', '夏至', '小暑', '大暑', '立秋', '处暑', '白露', '秋分',
	'寒露', '霜降', '立冬', '小雪', '大雪', '冬至', '小寒', '大寒'];

function jieqiRing(startShan, clockwise) {
	const i0 = SHAN_ORDER.indexOf(startShan);
	if (i0 < 0) { return []; }
	return JIEQI_24.map((jq, k)=>{
		const idx = clockwise ? (i0 + k) % 24 : ((i0 - k) % 24 + 24) % 24;
		const shan = SHAN_ORDER[idx];
		// 🔴 SHAN_ORDER 自壬起、壬在 345°：中心度须为 345+idx*15，用 idx*15 会整环偏一山。
		const center = norm360(345 + idx * 15);
		return { label: jq, shan, deg0: norm360(center - 7.5), deg1: norm360(center + 7.5) };
	}).sort((a, b)=>a.deg0 - b.deg0);
}
