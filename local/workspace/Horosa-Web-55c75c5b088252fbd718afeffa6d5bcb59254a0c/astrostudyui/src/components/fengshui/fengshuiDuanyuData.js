// 按星/卦检索断语：只回原文自身写明者（不做解读式匹配）。
export function duanyuFor({ stars = [], guas = [], src = '' } = {}) {
	// 显式传非数组（如字符串）会打穿默认值——先归一，否则 .map 抛。
	const ss = (Array.isArray(stars) ? stars : []).map(Number).filter((n)=>n >= 1 && n <= 9);
	const gg = (Array.isArray(guas) ? guas : []).filter(Boolean);
	return XUANKONG_DUANYU.filter((d)=>{
		if (src && d.src !== src) { return false; }
		if (!ss.length && !gg.length) { return false; }
		const hitS = ss.length ? ss.some((n)=>d.stars.indexOf(n) >= 0) : false;
		const hitG = gg.length ? gg.some((g)=>d.guas.indexOf(g) >= 0) : false;
		return hitS || hitG;
	});
}

// 按飞星盘逐宫检索：宫内山星/向星/运星 + 该宫之卦，凡赋文写明者即列出。
export function duanyuByPan(palaces = []) {
	return (Array.isArray(palaces) ? palaces : []).map((p)=>{
		const stars = [p.shan, p.xiang, p.yun].filter((n)=>n != null);
		const hits = duanyuFor({ stars, guas: p.gua ? [p.gua] : [] });
		return { gong: p.gong, gua: p.gua, dir: p.dir || p.name, stars, hits };
	}).filter((r)=>r.hits.length);
}

