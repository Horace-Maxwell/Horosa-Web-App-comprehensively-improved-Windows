// 扁平索引：城市名 → { prov, dec }（城市名去「市」后亦可查，便于用户输入）。
export const DECLINATION_INDEX = (()=>{
	const m = {};
	Object.keys(DECLINATION_TABLE).forEach((prov)=>{
		DECLINATION_TABLE[prov].forEach(([city, dec])=>{
			m[city] = { prov, city, dec };
			const bare = city.replace(/[市州盟地区]$/, '');
			if (bare && bare !== city && !m[bare]) { m[bare] = { prov, city, dec }; }
		});
	});
	return m;
})();

export const DECLINATION_CITY_COUNT = Object.keys(DECLINATION_TABLE)
	.reduce((a, p)=>a + DECLINATION_TABLE[p].length, 0);

// 查磁偏角：先精确、后去后缀、再前缀匹配；查不到返回 null（不猜）。
export function declinationOf(name) {
	if (!name) { return null; }
	const k = String(name).trim();
	if (DECLINATION_INDEX[k]) { return DECLINATION_INDEX[k]; }
	const hit = Object.keys(DECLINATION_INDEX).find((c)=>c.indexOf(k) === 0 || k.indexOf(c) === 0);
	return hit ? DECLINATION_INDEX[hit] : null;
}

// 真方位角 → 罗盘磁向（加磁偏角）。source='wmm' 时先取负（东偏为正 → 西偏为正）。
export function trueToMagnetic(trueDeg, dec, source = 'book') {
	const t = Number(trueDeg); const d = Number(dec);
	if (!Number.isFinite(t) || !Number.isFinite(d)) { return null; }
	const eff = source === 'wmm' ? -d : d;
	return { magnetic: ((t + eff) % 360 + 360) % 360, applied: eff, source,
		note: source === 'wmm' ? 'WMM／IGRF 东偏为正，已取负后代入' : '本表西偏为正，直接相加' };
}
