// 取一张牌的传统义(返回 {up,rev} 或 null=该条目未录,消费端隐藏传统层)。
export function traditionalMeaningOf(card){
	if(!card){ return null; }
	if(isTrumpArcana(card.arcana)){ return TRAD_MAJOR[card.sid] || null; }
	if(card.court){ return (TRAD_COURT[card.suit] && TRAD_COURT[card.suit][card.court]) || null; }
	if(card.number >= 1 && card.number <= 10){ return (TRAD_PIP[card.suit] && TRAD_PIP[card.suit][card.number]) || null; }
	return null;
}
