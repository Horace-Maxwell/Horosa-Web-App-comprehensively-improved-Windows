const PLACE_LABEL_RE = /^出生地[:：]/;
const PLACE_KEEP = new Set(Array.from('里托克布扎于采范'));
const BOUNDARY_RE = /^[^\p{L}\p{N}]?$/u;   // 串首尾(undefined → '')/ 标点 / 空白

// 预编译:每个字 → [[词码点数组, 繁体码点数组, 该字在词中的位置], …](长词优先,同一字在词中多次出现各占一条)
const INDEX = {};
Object.keys(RULES).forEach((ch)=>{
	const list = [];
	Object.keys(RULES[ch].words).forEach((w)=>{
		const sw = Array.from(w);
		const tw = Array.from(RULES[ch].words[w]);
		if(sw.length !== tw.length){ return; }
		sw.forEach((c, off)=>{ if(c === ch){ list.push([sw, tw, off]); } });
	});
	list.sort((a, b)=>b[0].length - a[0].length);
	INDEX[ch] = list;
});

// 白名单词逐字比:原文该位是简体写法或繁体写法都算(已转过的文字再转一次不变)
function matchAt(src, start, word, tword){
	if(start < 0 || start + word.length > src.length){ return false; }
	for(let k = 0; k < word.length; k += 1){
		const c = src[start + k];
		if(c !== word[k] && c !== tword[k]){ return false; }
	}
	return true;
}

const NEVER = ()=>false;

function contextDecides(ctx, s, i){
	const l = s[i - 1];
	const r = s[i + 1];
	if(ctx.foreign.has(l) || ctx.foreign.has(r)){ return false; }
	if(r === '制'){ return ctx.domain.has(l) || ctx.zhiObject.has(s[i + 2]); }
	if(ctx.domain.has(l) || ctx.domain.has(r)){ return true; }
	return BOUNDARY_RE.test(l || '') && BOUNDARY_RE.test(r || '');
}

// src = 原文,conv = 通用词典的转换结果;回逐位校正后的繁体。
// opts.isTradOnly(ch):ch 是否繁体专用字(简体原文里不会出现);opts.isTradChar(ch):ch 在繁体里是否通行。
// 缺省一律否(纯规则测试用,等于不启用「原文已是繁体则不改」)。
// opts.trace(数组,测试用):逐个校正位记下 [位, 字, 依据, 白名单词的 [起位, 长度] 或 null](依据:word / guard / trad / ctx-domain / ctx-dict / quote / def / place)。
export function applyHantDomainRules(src, conv, opts){
	const s = Array.from(`${src}`);
	const t = Array.from(`${conv}`);
	if(s.length !== t.length){ return `${conv}`; }
	const isTradOnly = (opts && typeof opts.isTradOnly === 'function') ? opts.isTradOnly : NEVER;
	const isTradChar = (opts && typeof opts.isTradChar === 'function') ? opts.isTradChar : NEVER;
	const inTradText = (i)=>((s[i - 1] !== undefined && isTradOnly(s[i - 1])) || (s[i + 1] !== undefined && isTradOnly(s[i + 1])));
	const trace = (opts && Array.isArray(opts.trace)) ? opts.trace : null;
	const placeLabel = PLACE_LABEL_RE.test(s.slice(0, 4).join(''));
	for(let i = 0; i < s.length; i += 1){
		if(placeLabel && PLACE_KEEP.has(s[i])){
			if(trace){ trace.push([i, s[i], 'place', null]); }
			t[i] = s[i];
			continue;
		}
		const rule = RULES[s[i]];
		if(!rule){
			if(t[i] !== s[i] && isTradChar(s[i]) && inTradText(i)){ t[i] = s[i]; }   // 原文本身是繁体:照原文
			continue;
		}
		const cands = INDEX[s[i]];
		let out = null;
		let how = 'word';
		let span = null;
		let vetoed = null;
		for(let j = 0; j < cands.length; j += 1){
			const [sw, tw, off] = cands[j];
			if(!matchAt(s, i - off, sw, tw)){ continue; }
			const gs = guardsOf(s[i], sw);
			const failed = gs.find((g)=>!guardAllows(g, s, i - off, sw.length));
			if(failed){ if(!vetoed){ vetoed = failed; } continue; }
			out = tw[off]; span = [i - off, sw.length]; break;
		}
		if(out === null && vetoed && vetoed.alt){
			out = vetoed.alt; how = 'guard';
		}
		if(out === null){
			const r = s[i + 1];
			if(isTradChar(s[i]) && inTradText(i)){
				out = s[i]; how = 'trad';                           // 原文本身是繁体:照原文
			}else if(rule.ctx && rule.ctxHit){
				const hit = CTX[rule.ctx](s, i);                    // 上下文成立取 ctxHit,否则取本域缺省字(不看词典)
				out = hit ? rule.ctxHit : rule.def; how = hit ? 'ctx-domain' : 'def';
			}else if(rule.ctx){
				const dom = CTX[rule.ctx](s, i);
				out = dom ? rule.def : t[i]; how = dom ? 'ctx-domain' : 'ctx-dict';
			}else if(rule.quote && QUOTE_FOLLOW.has(r)){
				out = s[i]; how = 'quote';
			}else{
				out = rule.def === null ? t[i] : rule.def; how = 'def';
			}
		}
		if(trace){ trace.push([i, s[i], how, span]); }
		t[i] = out;
	}
	return t.join('');
}

