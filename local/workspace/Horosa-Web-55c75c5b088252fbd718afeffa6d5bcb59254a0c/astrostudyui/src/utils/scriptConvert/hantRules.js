const isBlank = (c)=>c === ' ' || c === '\u3000' || c === '\t';
function neighbor(src, at, step){
	let k = at;
	while(k >= 0 && k < src.length && isBlank(src[k])){ k += step; }
	return k >= 0 && k < src.length ? src[k] : '';
}

// 一个白名单词可同时受两类判据:本词判据(WORD_GUARDS)/ 词边字判据(EDGE_GUARDS:以该字开头)/ 词尾字判据(TAIL_GUARDS:以该字收尾);
// 都要通过才算命中
function guardsOf(ch, sw){
	const w = sw.join('');
	const out = [];
	if(WORD_GUARDS[w]){ out.push(WORD_GUARDS[w]); }
	const eg = EDGE_GUARDS[ch];
	if(sw[0] === ch && eg && (!eg.words || eg.words.indexOf(w) >= 0)){ out.push(eg); }
	const tg = TAIL_GUARDS[ch];
	if(sw.length > 1 && sw[sw.length - 1] === ch && tg){ out.push(tg); }
	return out;
}
function guardOf(ch, sw){
	const g = guardsOf(ch, sw);
	return g.length ? g[0] : null;
}

function guardAllows(g, src, start, len){
	if(!g){ return true; }
	const l = neighbor(src, start - 1, -1);
	const r = neighbor(src, start + len, 1);
	if(g.notLeft && l && g.notLeft.indexOf(l) >= 0){ return false; }
	if(g.notRight && r && g.notRight.indexOf(r) >= 0){ return false; }
	if(g.onlyLeft && l && !BOUNDARY_RE.test(l) && g.onlyLeft.indexOf(l) < 0){ return false; }
	if(g.onlyLeftStrict && (!l || g.onlyLeftStrict.indexOf(l) < 0)){ return false; }
	return true;
}

