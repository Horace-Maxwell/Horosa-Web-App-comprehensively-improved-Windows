const OpenCC = require('opencc-js/dist/umd/cn2t.js');

describe('词典前提', () => {
	it('简 → 繁(台湾字形)词典逐码点等长 —— 逐位校正依赖它', () => {
		const parse = (d) => (typeof d === 'string' ? d.split('|').map((x) => x.split(' ')) : d);
		const all = [...OpenCC.Locale.from.cn[0].flatMap(parse), ...OpenCC.Locale.to.tw.flat().flatMap(parse)];
		expect(all.length).toBeGreaterThan(50000);
		const unequal = all.filter(([k, v]) => v !== undefined && Array.from(k).length !== Array.from(v).length);
		expect(unequal).toEqual([]);
	});
	it('逐码点等长 ≠ UTF-16 等长:转换前后 UTF-16 长度不同的字对与登记表一致(词典升级多出新字即红)', () => {
		// 扩展 A 区有字转繁后落到辅助平面(㓆 → 𠗣),规范简化字里的扩展 E / F 字转繁后回到基本平面(𬣙 → 訏)。
		// 检索比对与高亮按码点对齐、经下标换算表落回(scriptMatch.js),不能拿 UTF-16 下标直接对位。
		const parse = (d) => (typeof d === 'string' ? d.split('|').map((x) => x.split(' ')) : d);
		const all = [...OpenCC.Locale.from.cn[0].flatMap(parse), ...OpenCC.Locale.to.tw.flat().flatMap(parse)];
		const pairs = new Set();
		all.forEach(([k, v]) => {
			if (v === undefined || k.length === v.length) { return; }
			const a = Array.from(k);
			const b = Array.from(v);
			a.forEach((c, i) => { if (c.length !== b[i].length) { pairs.add(c + b[i]); } });
		});
		const saved = new Set(require('./hantUtf16Pairs.fixture.json').pairs.split(' '));
		expect([...pairs].filter((x) => !saved.has(x)).sort()).toEqual([]);
		expect([...saved].filter((x) => !pairs.has(x)).sort()).toEqual([]);
		expect(saved.has('㓆𠗣') && saved.has('𬣙訏')).toBe(true);   // 两个方向都有
		// 真转换器同样:逐码点等长,UTF-16 不等长
		['㓆', '𬣙', '王𬣙的后天八卦'].forEach((x) => {
			expect(Array.from(toHant(x)).length).toBe(Array.from(x).length);
			expect(toHant(x).length).not.toBe(x.length);
		});
	});
});

