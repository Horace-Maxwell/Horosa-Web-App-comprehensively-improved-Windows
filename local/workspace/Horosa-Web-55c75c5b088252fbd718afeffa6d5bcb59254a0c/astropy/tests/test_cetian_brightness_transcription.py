def test_yiyu_brightness_matches_book_cell_by_cell():
    assert set(CETIAN_BRIGHTNESS_TABLE_YIYU) == set(BOOK), "星名集与诸星格十九格不符"
    for star, cells in BOOK.items():
        want = {B.index(zhi): label for zhi, label in cells.items()}
        got = CETIAN_BRIGHTNESS_TABLE_YIYU[star]
        missing = {B[k]: v for k, v in want.items() if got.get(k) != v}
        extra = {B[k]: v for k, v in got.items() if want.get(k) != v}
        assert not missing and not extra, f"{star}格 漏/错:{missing} 多:{extra}"


def test_yiyu_labels_legal_and_nonempty():
    legal = {"廟", "旺", "樂", "廟旺"}
    for star, cells in CETIAN_BRIGHTNESS_TABLE_YIYU.items():
        assert cells, f"{star} 全表为空（移语本诸星格每星皆有庙旺标注）"
        for b, label in cells.items():
            assert 0 <= b <= 11, f"{star} 支越界 {b}"
            assert label in legal, f"{star}{B[b]} 非法标注 {label}"
