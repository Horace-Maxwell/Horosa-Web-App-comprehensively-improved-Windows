#!/usr/bin/env node
// P2-5 (v2.5.4 hardening): generate winget (Windows Package Manager) manifests for the current release.
//
// Adds a `winget install HoraceMaxwell.Horosa` path (discoverability + scriptable/enterprise installs)
// WITHOUT replacing the NSIS download. winget accepts an unsigned EXE installer given a SHA-256.
//
// Emits the 3 required manifests under  winget/manifests/h/HoraceMaxwell/Horosa/<version>/  :
//   HoraceMaxwell.Horosa.yaml                (version manifest)
//   HoraceMaxwell.Horosa.installer.yaml      (installer manifest, InstallerType: nullsoft, Scope: user)
//   HoraceMaxwell.Horosa.locale.en-US.yaml   (default-locale manifest)
//
// USAGE:
//   node scripts/winget-manifest.cjs            # version from package.json, sha256 from release/SHA256SUMS.txt
//   node scripts/winget-manifest.cjs <version> <sha256-hex>
//
// SUBMIT (manual, when you want winget to carry the release):
//   copy winget/manifests/... into a fork of microsoft/winget-pkgs and open a PR (or use `wingetcreate`).
//   The manifests here are the source of truth / template; winget-pkgs is a separate repo.

'use strict';

const fs = require('fs');
const path = require('path');

const PKG_ID = 'HoraceMaxwell.Horosa';
const OWNER = 'Horace-Maxwell';
const REPO = 'Horosa-Web-App-comprehensively-improved-Windows';
const MANIFEST_VERSION = '1.6.0';

function readVersion() {
  return require('../package.json').version;
}

function readSha256FromSums(version) {
  const sums = path.join(__dirname, '..', 'release', 'SHA256SUMS.txt');
  if (!fs.existsSync(sums)) return null;
  const line = fs.readFileSync(sums, 'utf8').split(/\r?\n/).find((l) => l.includes(`Horosa-Setup-${version}.exe`) && !l.includes('.blockmap'));
  return line ? line.trim().split(/\s+/)[0].toUpperCase() : null;
}

function main() {
  const version = process.argv[2] || readVersion();
  // The generator runs on release day (right after the build), so "today" IS the
  // release date. This used to be a hardcoded literal that needed a manual bump
  // every release -- v2.6.4 forgot winget entirely and v2.6.5 shipped manifests
  // carrying the previous version's date until edited by hand.
  const releaseDate = new Date().toISOString().slice(0, 10);
  let sha256 = process.argv[3] || readSha256FromSums(version);
  if (!sha256) {
    console.error(`[winget] could not resolve SHA-256 for v${version} (no release/SHA256SUMS.txt and none passed).`);
    process.exit(2);
  }
  sha256 = sha256.toUpperCase();
  const installerUrl = `https://github.com/${OWNER}/${REPO}/releases/download/v${version}/Horosa-Setup-${version}.exe`;

  const outDir = path.join(__dirname, '..', '..', 'winget', 'manifests', 'h', 'HoraceMaxwell', 'Horosa', version);
  fs.mkdirSync(outDir, { recursive: true });

  const versionManifest = `# Generated by scripts/winget-manifest.cjs
PackageIdentifier: ${PKG_ID}
PackageVersion: ${version}
DefaultLocale: en-US
ManifestType: version
ManifestVersion: ${MANIFEST_VERSION}
`;

  const installerManifest = `# Generated by scripts/winget-manifest.cjs
PackageIdentifier: ${PKG_ID}
PackageVersion: ${version}
InstallerLocale: en-US
Platform:
  - Windows.Desktop
MinimumOSVersion: 10.0.0.0
InstallerType: nullsoft
Scope: user
InstallModes:
  - interactive
  - silent
  - silentWithProgress
UpgradeBehavior: install
ReleaseDate: ${releaseDate}
Installers:
  - Architecture: x64
    InstallerUrl: ${installerUrl}
    InstallerSha256: ${sha256}
ManifestType: installer
ManifestVersion: ${MANIFEST_VERSION}
`;

  const localeManifest = `# Generated by scripts/winget-manifest.cjs
PackageIdentifier: ${PKG_ID}
PackageVersion: ${version}
PackageLocale: en-US
Publisher: ${OWNER}
PublisherUrl: https://github.com/${OWNER}
PackageName: Horosa
PackageUrl: https://github.com/${OWNER}/${REPO}
License: AGPL-3.0-only
LicenseUrl: https://github.com/${OWNER}/${REPO}/blob/main/LICENSE
ShortDescription: Western astrology and Chinese metaphysics in one native Windows workstation.
Description: |-
  Horosa (星阙) is a desktop workstation for traditional cosmology: Western astrology (natal, the full
  timing chain, relationship work) alongside Chinese systems (Bazi, Ziwei, Qimen, Liuren, Taiyi), in one
  native Windows app with an offline self-contained Python/Java runtime bundled in.
Tags:
  - astrology
  - metaphysics
  - bazi
  - ziwei
  - 占星
ManifestType: defaultLocale
ManifestVersion: ${MANIFEST_VERSION}
`;

  fs.writeFileSync(path.join(outDir, `${PKG_ID}.yaml`), versionManifest);
  fs.writeFileSync(path.join(outDir, `${PKG_ID}.installer.yaml`), installerManifest);
  fs.writeFileSync(path.join(outDir, `${PKG_ID}.locale.en-US.yaml`), localeManifest);

  console.log(`[winget] wrote 3 manifests for v${version} to:\n  ${outDir}`);
  console.log(`  InstallerSha256 = ${sha256}`);
  console.log('  submit: fork microsoft/winget-pkgs, copy under manifests/h/HoraceMaxwell/Horosa/, open PR (or use wingetcreate).');
}

main();
